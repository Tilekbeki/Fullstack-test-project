CREATE TABLE IF NOT EXISTS responsibles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE CHECK (length(btrim(name)) > 0)
);

CREATE TABLE IF NOT EXISTS projects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    owner_id INTEGER NOT NULL REFERENCES responsibles(id) ON DELETE RESTRICT,
    budget NUMERIC(12, 2) NOT NULL CHECK (budget >= 0),
    start_date DATE NOT NULL,
    priority INTEGER NOT NULL CHECK (priority BETWEEN 1 AND 3)
);

CREATE TABLE IF NOT EXISTS tasks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    title VARCHAR(160) NOT NULL,
    assignee VARCHAR(100) NOT NULL,
    estimate NUMERIC(8, 1) NOT NULL CHECK (estimate >= 0),
    due_date DATE NOT NULL,
    status_code INTEGER NOT NULL CHECK (status_code BETWEEN 1 AND 3)
);

CREATE INDEX IF NOT EXISTS tasks_project_id_idx ON tasks (project_id);
CREATE INDEX IF NOT EXISTS projects_owner_id_idx ON projects (owner_id);

