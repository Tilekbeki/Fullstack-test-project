-- Upgrade an existing database that stores the responsible's name in projects.owner.
-- This migration is transactional and safe to run again.
BEGIN;

CREATE TABLE IF NOT EXISTS responsibles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE CHECK (length(btrim(name)) > 0)
);

ALTER TABLE projects ADD COLUMN IF NOT EXISTS owner_id INTEGER;

DO $migration$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema() AND table_name = 'projects' AND column_name = 'owner'
    ) THEN
        INSERT INTO responsibles (name)
        SELECT DISTINCT btrim(owner) FROM projects
        WHERE owner IS NOT NULL AND btrim(owner) <> ''
        ON CONFLICT (name) DO NOTHING;

        UPDATE projects AS project
        SET owner_id = responsible.id
        FROM responsibles AS responsible
        WHERE project.owner_id IS NULL AND btrim(project.owner) = responsible.name;
    END IF;
END
$migration$;

ALTER TABLE projects ALTER COLUMN owner_id SET NOT NULL;

DO $migration$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'projects'::regclass AND conname = 'projects_owner_id_fkey'
    ) THEN
        ALTER TABLE projects ADD CONSTRAINT projects_owner_id_fkey
            FOREIGN KEY (owner_id) REFERENCES responsibles(id) ON DELETE RESTRICT;
    END IF;
END
$migration$;

CREATE INDEX IF NOT EXISTS projects_owner_id_idx ON projects (owner_id);
ALTER TABLE projects DROP COLUMN IF EXISTS owner;

COMMIT;
